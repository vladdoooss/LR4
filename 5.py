def find_common_assortment(store_inventories):
    # Перевіряємо, чи список магазинів не порожній
    if not store_inventories:
        print("Список магазинів порожній. Неможливо знайти спільні товари.")
        return set()
    # Перетин (товари, що є в усіх магазинах) - Множина А
    base_set = store_inventories[0]
    other_sets = store_inventories[1:]
    common_products_A = base_set.intersection(*other_sets)
    # Об'єднання (усі унікальні товари, що є хоча б десь)
    # Починаємо з порожньої множини і додаємо всі
    all_products = set()
    for inventory in store_inventories:
        all_products.update(inventory)  # .update() - це операція об'єднання

    print("           ІНФОРМАЦІЯ ПРО ВСІ МАГАЗИНИ")
    print(f"Всього проаналізовано магазинів: {len(store_inventories)}")

    print("\n--- Асортимент кожного магазину ---")
    for i, inventory in enumerate(store_inventories):
        # Додаємо виведення кількості товарів
        print(f"  Магазин {i + 1} (кількість позицій: {len(inventory)}):")
        print(f"    {inventory}")
    print(f"Загальний асортимент (усі унікальні товари): {len(all_products)} од.")
    print(f"    Список: {all_products}")
    print("     РЕЗУЛЬТАТ (товари, які є В УСІХ магазинах)")
    print(f"Множина А (спільні товари): {common_products_A}")
    print(f"Всього знайдено: {len(common_products_A)} спільних товарів.")
    return common_products_A
