my_list = ['apple', 'banana', 'cherry', 'date', 'fig']
# Друкуємо вхідні дані
print(f"Заданий список: {my_list}")
# Отримуємо цільовий елемент
target = input("Введіть елемент, сусідів якого треба знайти: ")
print(f"Шукаємо сусідів для елемента: '{target}'")
# 4. Виконуємо пошук та виводимо результат
try:
    # 4.1. Знаходимо індекс (позицію) нашого елемента
    index = my_list.index(target)
    # 4.2. Визначаємо, чи є сусіди
    only_left = index > 0
    only_right = index < (len(my_list) - 1)
    # 4.3. Виводимо результат залежно від того, де елемент
    if not only_left and not only_right:
            # Це єдиний елемент у списку
            print("Елемент єдиний у списку, в нього немає сусідів.")
    elif not only_left:
            # Це перший елемент (індекс 0)
            print("Це перший елемент.")
            print(f"Лівого сусіда немає.")
            print(f"Правий сусід: {my_list[index + 1]}")
    elif not only_right:
            # Це останній елемент
            print("Це останній елемент.")
            print(f"Лівий сусід: {my_list[index - 1]}")
            print(f"Правого сусіда немає.")
    else:
            # Елемент знаходиться всередині списку
            print("Елемент знайдено всередині списку.")
            print(f"Лівий сусід: {my_list[index - 1]}")
            print(f"Правий сусід: {my_list[index + 1]}")
except ValueError:
    # Ця помилка виникає, якщо my_list.index() не знаходить елемент
    print(f"Помилка: Елемент '{target}' не знайдено у списку.")
