# Визначаємо розміри масиву
ROWS = 7
COLS = 7

# Створюємо порожній список, який буде нашим двовимірним масивом (списком списків)
matrix = []

# Зовнішній цикл: ітеруємо по рядках (від 0 до 6)
for i in range(ROWS):
    # Для кожного рядка 'i' створюємо новий порожній список (це буде наш рядок)
    new_row = []
    # Внутрішній цикл: ітеруємо по стовпцях (від 0 до 6)
    for j in range(COLS):
        # Перевіряємо, чи є індекс стовпця 'j' парним
        if j % 2 == 0:
            # Якщо індекс парний (0, 2, 4, 6), додаємо 1
            new_row.append(1)
        else:
            # Якщо індекс непарний (1, 3, 5), додаємо 0
            new_row.append(0)
    # Після того, як внутрішній цикл заповнив рядок,
    # додаємо цей готовий рядок до основного масиву (matrix)
    matrix.append(new_row)

print(f"Згенерований масив 7x7:")
# Ітеруємо по кожному готовому рядку в масиві
for row in matrix:
    # Ітеруємо по кожному елементу (числу) в рядку
    for element in row:
        # 'end=" "' каже Python друкувати пробіл замість
        # переходу на новий рядок після кожного числа
        print(element, end=" ")
    # Після того, як всі числа в рядку надруковані,
    # робимо один перехід на новий рядок, щоб почати наступний
    print()